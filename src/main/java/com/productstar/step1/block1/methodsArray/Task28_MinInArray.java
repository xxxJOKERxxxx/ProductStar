package com.productstar.step1.block1.methodsArray;   // ← пакет, где лежит класс (папка в проекте)

import java.util.Scanner;                             // ← импортируем Scanner для ввода с клавиатуры

public class Task28_MinInArray {                      // ← объявляем публичный класс с именем файла

    // ============================================================
    // ГЛАВНЫЙ МЕТОД (точка входа в программу)
    // ============================================================
    public static void main(String[] args) {          // ← main — запускается первой при старте

        // 1. СОЗДАЁМ ИНСТРУМЕНТ ДЛЯ ВВОДА
        Scanner scanner = new Scanner(System.in);      // ← scanner умеет читать то, что печатает пользователь

        // 2. ЗАПРАШИВАЕМ РАЗМЕР МАССИВА
        System.out.print("Введите размер массива: ");  // ← выводим текст (print — без перевода строки)
        int size = scanner.nextInt();                  // ← читаем целое число, которое ввел пользователь

        // 3. СОЗДАЁМ МАССИВ
        int[] numbers = new int[size];                 // ← выделяем память под size ячеек (все ячейки пока = 0)

        // 4. ЗАПОЛНЯЕМ МАССИВ ЧИСЛАМИ ОТ ПОЛЬЗОВАТЕЛЯ
        System.out.println("Введите " + size + " чисел:");  // ← подсказка, сколько чисел нужно ввести
        for (int i = 0; i < numbers.length; i++) {     // ← i = 0; пока i меньше длины массива; увеличиваем i на 1
            System.out.print("Число " + (i + 1) + ": "); // ← подсказка: "Число 1: ", "Число 2: " и т.д.
            numbers[i] = scanner.nextInt();            // ← читаем число и сохраняем его в ячейку i
        }

        // 5. ВЫЗЫВАЕМ МЕТОД И СОХРАНЯЕМ РЕЗУЛЬТАТ
        int result = findMin(numbers);                 // ← передаём массив в метод, метод возвращает минимум, кладём в result

        // 6. ВЫВОДИМ РЕЗУЛЬТАТ
        System.out.println("Минимальное число в массиве: " + result);  // ← печатаем ответ

    } // ← конец метода main

    // ============================================================
    // МЕТОД: ПОИСК МИНИМАЛЬНОГО ЧИСЛА В МАССИВЕ
    // ============================================================
    public static int findMin(int[] numbers) {         // ← метод принимает массив, возвращает int

        // 1. ПРЕДПОЛАГАЕМ, ЧТО ПЕРВЫЙ ЭЛЕМЕНТ — МИНИМАЛЬНЫЙ
        int min = numbers[0];                          // ← берём первый элемент массива (индекс 0) как начальный минимум

        // 2. ПРОХОДИМ ПО ВСЕМ ЯЧЕЙКАМ, НАЧИНАЯ СО ВТОРОЙ
        for (int i = 1; i < numbers.length; i++) {     // ← i = 1 (второй элемент); идём до конца массива
            if (numbers[i] < min) {                    // ← если текущий элемент МЕНЬШЕ текущего минимума
                min = numbers[i];                      // ← то обновляем минимум (запоминаем новый)
            }
        }

        // 3. ВОЗВРАЩАЕМ РЕЗУЛЬТАТ
        return min;                                    // ← возвращаем найденное минимальное число

    } // ← конец метода findMin

} // ← конец класса Task28_MinInArray
